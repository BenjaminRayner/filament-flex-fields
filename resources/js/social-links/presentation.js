/** Reconcile keyed rows in place: SSR controls remain the live controls. */
export function createSocialPresentation(root, config) {
    const list = root.querySelector('[data-social-list]')
    const template = root.querySelector('[data-social-template]')
    const empty = root.querySelector('[data-social-empty]')
    const add = root.querySelector('[data-social-add]')
    const definitions = new Map(config.platforms.map(p => [p.value, p]))
    const rows = new Map([...list.children].map(node => [node.dataset.platform, capture(node)]))
    function capture(node) {
        return { node, input: node.querySelector('[data-social-url]'), icon: node.querySelector('[data-social-icon]'),
            label: node.querySelector('[data-social-label]'), error: node.querySelector('[data-social-error]'),
            actions: [...node.querySelectorAll('[data-social-action]')] }
    }
    return {
        render(links, errors, locked, canAdd) {
            const wanted = new Set(links.map(link => link.platform))
            for (const [key, row] of rows) if (!wanted.has(key)) { row.node.remove(); rows.delete(key) }
            links.forEach((link, index) => {
                let row = rows.get(link.platform)
                if (!row) {
                    row = capture(template.content.firstElementChild.cloneNode(true))
                    row.node.dataset.platform = link.platform
                    rows.set(link.platform, row)
                }
                const definition = definitions.get(link.platform)
                if (!row.prepared) {
                    row.label.textContent = definition?.label ?? link.platform
                    // Markup is generated by trusted PHP icon configuration, never submitted state.
                    const icon = config.brandIcons[link.platform] ?? ''
                    if (row.icon.innerHTML !== icon) row.icon.innerHTML = icon
                    row.input.id = `${root.dataset.socialOwner}-${link.platform}`
                    row.error.id = `${row.input.id}-error`
                    row.input.setAttribute('aria-describedby', row.error.id)
                    row.input.setAttribute('aria-label', `${row.label.textContent} ${config.labels.url}`)
                    row.input.placeholder = definition?.placeholder ?? 'https://'
                    row.prepared = true
                }
                if (row.input.value !== link.url) row.input.value = link.url
                row.input.disabled = !!config.disabled
                row.input.readOnly = locked
                row.actions.forEach(button => {
                    const action = button.dataset.socialAction
                    button.disabled = locked || (action === 'up' && index === 0) || (action === 'down' && index === links.length - 1)
                    const label = action === 'up' ? config.labels.moveUp : action === 'down' ? config.labels.moveDown : config.labels.remove
                    button.setAttribute('aria-label', `${label} ${row.label.textContent}`)
                })
                row.error.textContent = errors[index] ?? ''
                row.error.hidden = !errors[index]
                row.input.setAttribute('aria-invalid', errors[index] ? 'true' : 'false')
                row.input.closest('.fff-flex-text-input').classList.toggle('is-invalid', !!errors[index])
                if (list.children[index] !== row.node) list.insertBefore(row.node, list.children[index] ?? null)
            })
            empty.hidden = links.length > 0
            add.disabled = !canAdd
        },
        focus(platform) { rows.get(platform)?.input.focus() },
        destroy() { rows.clear() },
    }
}
