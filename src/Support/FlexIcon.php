    public static function make(string $icon): string
    {
        $normalized = str($icon)->replace('_', '-')->kebab()->toString();
        $normalized = str_starts_with($normalized, self::PREFIX) ? substr($normalized, strlen(self::PREFIX)) : $normalized;
        if (! preg_match('/^[a-z0-9]+(?:-[a-z0-9]+)*$/D', $normalized) || strlen($normalized) > 120) {
            throw new \InvalidArgumentException('Invalid Hugeicons name.');
        }

        return self::PREFIX.(self::SEMANTIC_NAMES[$normalized] ?? $normalized);
    }

    /** Published v3 configuration must not restore the removed Gravity icon set. */
    public static function configured(string $key, string $fallback): string
    {
        $icon = config('filament-flex-fields.ui.'.$key);

        return is_string($icon) && (str_starts_with($icon, self::PREFIX) || str_starts_with($icon, 'flexhugeicons-'))
            ? $icon
            : $fallback;
    }

